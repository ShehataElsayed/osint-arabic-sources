"""Trains the case planner on data/planner_cases.json (synthetic, ours). Held-out: last 3 cases per type, model trained on the first 9. Writes oshai_tools/planner_model.py trained on all 12."""
import json, sys, os, statistics
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from oshai_tools import t_planner as P
SPREAD = float(sys.argv[1]) if len(sys.argv) > 1 else 1.5
D = json.load(open(os.path.join(os.path.dirname(__file__), "..", "oshai_tools", "data", "planner_cases.json"), encoding="utf-8"))["cases"]
def prune(m):
    m["w"] = {w: v for w, v in m["w"].items() if max(v.values()) - min(v.values()) > SPREAD}; return m
tr = {c: v[:9] for c, v in D.items()}; te = [(c, x) for c, v in D.items() for x in v[9:]]
m = prune(P.train(tr)); ok = 0
for c, x in te:
    p, _ = P.scores(m, x); ok += max(p, key=p.get) == c
print("spread", SPREAD, "held-out", ok, "/", len(te), "features", len(m["w"]))
full = prune(P.train(D))
src = '"""Weights of the case planner. Synthetic training cases written by us (12 per type, 12 types); held-out check on 3 cases per type (model trained on the other 9) gave %d/%d top-1 correct. NOT validated on real investigations. Generated by evals/train_planner.py."""\nMODEL = %s\n' % (ok, len(te), json.dumps(full, ensure_ascii=False, separators=(",", ":")))
open(os.path.join(os.path.dirname(__file__), "..", "oshai_tools", "planner_model.py"), "w", encoding="utf-8").write(src); print(len(src) // 1024, "KB")
