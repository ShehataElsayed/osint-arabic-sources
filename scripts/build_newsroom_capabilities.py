#!/usr/bin/env python3
"""Full handbook inventory, never promotes metadata to executable adapters."""
import hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parent.parent
items=[]
def walk(node,parents=()):
    if node.get('type')=='url':
        identity='\0'.join((*parents,node.get('name',''),node.get('url','')))
        items.append({'id':'handbook-'+hashlib.sha256(identity.encode()).hexdigest()[:24], 'name':node.get('name',''), 'category':' / '.join(parents),'url':node.get('url',''),'input':str(node.get('input','')),'output':str(node.get('output','')),'mode':'discovery-only','catalogStatus':node.get('status','unknown'),'catalogPricing':node.get('pricing','unknown'),'apiClaim':bool(node.get('api'))})
    for child in node.get('children',[]):walk(child,(*parents,node.get('name','')) if parents or node.get('type')!='folder' or node.get('name')!='دليل المصادر المفتوحة للصحفيين العرب' else parents)
walk(json.loads((root/'2-data.json').read_text()))
raw_count=len(items)
items=list({x['id']:x for x in items}.values())
print('Exact duplicate records collapsed:',raw_count-len(items))
(root/'newsroom/handbook-capabilities.mjs').write_text('// Generated by scripts/build_newsroom_capabilities.py from2-data.json. Snapshot claims only.\nexport const HANDBOOK='+json.dumps(items,ensure_ascii=False,separators=(',',':'))+';\n')
print('Handbook entries:',len(items),'executable external services:0')
