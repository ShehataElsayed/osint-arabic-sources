#!/usr/bin/env python3
"""Generate site/journalist-media/planner-catalog.js from 2-data.json.

Curated snapshot for the verification-path planner: free + live external tools
from the guide categories the planner's rules can recommend. Regenerate with:
python3 scripts/build_planner_catalog.py
"""
import json, sys

CATEGORIES = {
    'Username', 'Telephone Numbers', 'Email Address', 'Social Networks',
    'Geolocation Tools / Maps', 'Images / Videos / Docs', 'Archives',
    'Disinformation & Media Verification', 'Documentation / Evidence Capture',
}
PER_CATEGORY = 6

def leaves(node, cat, out):
    for child in node.get('children', []):
        if child.get('type') == 'url':
            if child.get('pricing') == 'free' and child.get('status') == 'live':
                flags = (child.get('opsecNote', '') + ' ' + child.get('description', '')).lower()
                if any(t in flags for t in ('illegal','piracy','pirate','shadow librar','carry legal','copyright infringement')):
                    continue
                out.append((cat, child))
        else:
            leaves(child, cat, out)

def main():
    data = json.load(open('2-data.json'))
    picked = {}
    for top in data.get('children', []):
        name = top.get('name')
        if name not in CATEGORIES:
            continue
        found = []
        leaves(top, name, found)
        picked[name] = found[:PER_CATEGORY]
    entries = []
    for cat in sorted(picked):
        for cat_name, item in picked[cat]:
            entries.append({
                'cat': cat_name,
                'name': item.get('name'),
                'url': item.get('url'),
                'input': item.get('input', ''),
                'output': item.get('output', ''),
                'bestFor': item.get('bestFor', ''),
                'opsec': item.get('opsec', ''),
                'opsecNote': item.get('opsecNote', '')[:200],
            })
    body = '// GENERATED by scripts/build_planner_catalog.py from 2-data.json - do not edit by hand.\n'
    body += 'export const CATALOG=' + json.dumps(entries, ensure_ascii=False) + ';\n'
    with open('site/journalist-media/planner-catalog.js', 'w') as f:
        f.write(body)
    print('entries:', len(entries), 'categories:', len(picked))

if __name__ == '__main__':
    sys.exit(main())
