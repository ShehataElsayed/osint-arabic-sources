import json, re, unittest, hashlib
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit,unquote
ROOT=Path(__file__).resolve().parents[1]
class Links(HTMLParser):
    def __init__(self):super().__init__();self.links=[]
    def handle_starttag(self,tag,attrs):
        for k,v in attrs:
            if k in ('href','src') and v:self.links.append(v)
class Foundation(unittest.TestCase):
    def test_counts_and_descriptions(self):
        tree=json.loads((ROOT/'2-data.json').read_text());leaves=[]
        def walk(n):
            if n.get('url'):leaves.append(n)
            for c in n.get('children',[]):walk(c)
        walk(tree)
        self.assertEqual(len(tree['children']),33)
        self.assertEqual(len(leaves),1171)  # 2026-10-25: +Perma.cc, +archive.today, +Google Fact Check Explorer (verified live; CourtListener dup reverted)
        self.assertTrue(all(n.get('arDescription') for n in leaves))
    def test_review_queue_structure(self):
        # 2026-10-29: the queue is now populated by the first real audit. The guard
        # changes from "nothing reviewed" to "whatever is marked was structurally
        # verified": known statuses only, real ISO timestamps, no future dates,
        # and pending entries still carry no check date.
        import datetime
        reviews=json.loads((ROOT/'3-review-queue.json').read_text())
        self.assertEqual(len(reviews),1109)  # 2026-10-29 reconciliation: exactly one row per catalogue
        # unique URL. Repairs had created 3 duplicate rows (melissa.com, urlhaus.abuse.ch,
        # whatsmybrowser.org) and the audit had probed a phenoelit.org variant absent from the
        # catalogue; its row now tracks the real catalogue URL (phenoelit.de). All names and
        # notes from merged rows are preserved on the surviving row.
        known={'pending','ok','broken','server_error','unreachable','blocked','template'}
        required={'url','names','last_checked','review_status','evidence_url','notes','http_status'}
        now=datetime.datetime.now(datetime.timezone.utc)
        for r in reviews:
            self.assertTrue(required.issubset(set(r)),r['url'])
            self.assertIsInstance(r['names'],list,r['url'])
            self.assertIn(r['review_status'],known,r['url'])
            if r['review_status']!='pending':
                # raw observation must survive: numeric HTTP code for reachable hosts,
                # transport subtype in notes for unreachable ones
                if r['review_status'] in ('ok','broken','server_error','blocked') and r['http_status'] is None and '%3C' not in r['url']:
                    self.assertIsNotNone(r['http_status'],r['url'])
            if r['review_status']=='pending':
                self.assertIsNone(r['last_checked'],r['url'])
                continue
            self.assertIsNotNone(r['last_checked'],r['url'])
            ts=datetime.datetime.fromisoformat(r['last_checked'].replace('Z','+00:00'))
            self.assertLessEqual(ts,now,r['url'])
            self.assertGreaterEqual(ts,datetime.datetime(2026,10,29,tzinfo=datetime.timezone.utc),r['url'])
    def test_admin_preserved(self):
        # Built pages carry a content-hash ?v= on local js/css refs (cache busting); strip it to compare content.
        import re
        bust = re.compile(rb'\?v=[a-f0-9]{8}(")').sub
        self.assertEqual((ROOT/'site/admin.html').read_bytes(), bust(rb'\1', (ROOT/'_site/admin.html').read_bytes()))
    def test_required_pages(self):
        for f in ['index.html','admin.html','commands.html','methodology.html','verification.html','assistant.html','smart-search.html','catalog/category-01.html']:
            self.assertTrue((ROOT/'_site'/f).is_file(),f)
    def test_local_links(self):
        missing=[]
        for p in (ROOT/'_site').rglob('*.html'):
            parser=Links();parser.feed(p.read_text())
            for link in parser.links:
                u=urlsplit(link)
                if u.scheme or u.netloc or not u.path or u.path.startswith('data:'):continue
                if 'pagefind/' in u.path:continue # generated by pinned Pagefind after source build
                target=(p.parent/unquote(u.path)).resolve()
                if not target.exists():missing.append((str(p.relative_to(ROOT/'_site')),link))
        self.assertEqual(missing,[])
    def test_no_placeholders(self):
        self.assertNotIn('__DATA_JSON__',(ROOT/'_site/index.html').read_text())
    def test_font_and_credit(self):
        text=(ROOT/'_site/index.html').read_text()
        self.assertIn('صممت بواسطة مهندس شحاته السيد',text)
        self.assertIn('Cairo',text)
    def test_deploy_no_zip(self):
        text=(ROOT/'.github/workflows/deploy.yml').read_text()
        self.assertNotIn('unzip',text)
        self.assertIn('npm ci',text)
if __name__=='__main__':unittest.main()
